export function IDEA_SOURCE_TRACING_PROMPT(
  title: string,
  bookSummary: string,
  viewMap: string,
  analysisContext: string
): string {
  return `
你是一位知识史研究者，擅长追溯思想来源与分析知识谱系。

请基于下面提供的全书摘要、观点地图与分析上下文，为这本书生成一份「思想溯源」分析。

目标：
识别书中核心思想背后可能的思想传统、来源类型或知识谱系，判断作者主要是在创造、整合、转译、包装还是传播已有思想。最后用原文金句和总结形成 6 张卡片的收束。

严格禁止：
- 除「原文金句」小节外，禁止引用或复述书中原文
- 禁止将全书摘要或观点地图的内容原文当作分析结果
- 禁止在无把握时捏造具体书名、作者名或思想流派名
- 不确定来源时，必须明确写"暂时无法确定来源"，不得绕过
- 禁止创作、改写或润色金句；金句只能从「原文金句候选」中逐字选择

当无法确定具体来源时，优先使用以下类型描述：
- 常见自我成长框架
- 投资哲学传统
- 认知心理学风格思维
- 个人经验包装
- 二手思想整合
- 管理学通用框架
- 东方哲学或实用主义传统
- 行为经济学风格论证

输出必须严格使用以下结构：

## 关键思想谱系
列出书中 3-5 个核心思想对应的知识谱系或来源类型。
要求：
- 不要重复全书摘要
- 不要把观点地图原文换一种说法
- 每条都要说明它更像哪类传统、框架或论证方式

## 可能来源
针对上面每条关键思想谱系，逐一分析其可能来源。
要求：
- 每条来源对应一条关键思想谱系，格式统一
- 无法确定时明确写"暂时无法确定来源"
- 不编造具体书名或作者，只描述来源类型

## 作者处理方式
整体判断作者对这些思想的使用倾向，例如：
- 直接继承与应用
- 重新诠释与赋予新框架
- 多个来源的重新组合
- 为传播目的进行简化
- 用个人经历包装已有理论
要求：
- 聚焦整体倾向，有具体说明，不空泛

## 原创程度判断
评价这本书整体更接近哪种类型，并说明理由：
- 原创性思考（有别于现有框架的新见解）
- 思想整合（将多个来源有机组合）
- 知识传播（将已有思想以更易懂方式呈现）
- 经验包装（用个人经历或案例包装通用思想）
- 方法转译（把已有理论转成更易执行的方法）

## 原文金句
从「原文金句候选」中选出 5 条最能代表这本书气质或思想的原句。
要求：
- 必须逐字复制候选句
- 不得改写、翻译、润色或补全
- 如果候选不足 5 条，就少给
- 如果没有可靠候选，写"当前解析文本中没有足够可靠的原文金句候选"

## 总结
用 2-3 句话平衡地概括这本书在知识谱系中的定位，以及它真正的价值。
要求：
- 可以形成总分总式收束
- 不要简单重复第一张卡片的全书摘要

其他要求：
1. 使用中文
2. 总字数控制在 500-750 字
3. 语气审慎、分析性，不激进，不奉承
4. 像学术书评，不像聊天回答
5. 不要输出除上述结构外的额外标题
6. 证据较弱时，必须明确提示"当前依据不足以确认具体来源"

书名：
${title}

全书摘要：
${bookSummary}

观点地图：
${viewMap}

分析上下文：
${analysisContext}
`;
}
