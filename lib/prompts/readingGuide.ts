export function READING_GUIDE_PROMPT(
  title: string,
  bookSummary: string,
  analysisContext: string
): string {
  return `
你是一位经验丰富的阅读教练。

请基于下面提供的全书摘要与分析上下文，为这本书生成一份「阅读指南」。

目标：
帮助读者知道应该如何进入这本书：带着什么问题读、按什么路径读、重点读哪些部分、哪些部分可以跳读。

输出必须严格使用以下结构：

## 阅读定位
说明：
- 用 2-3 句话说明这本书适合带着什么期待读
- 不要重复全书摘要
- 不要重新介绍整本书讲什么

## 阅读三问
提出 3 个关键问题，让读者带着问题去读。
要求：
- 三个问题不能重复
- 三个问题必须覆盖整本书核心逻辑
- 问题要具体，不要空泛

## 阅读路径
说明：
- 建议先读什么，再读什么
- 哪些部分需要慢读
- 哪些部分可以跳读或按需查阅

## 重点章节
列出 3-5 个最值得读的章节、部分或样本位置。
要求：
- 每条说明为什么值得读
- 尽量结合分析上下文里的目录、章节标题或依据提示

## 当代意义
说明：
- 这本书对今天的读者有什么启发
- 它解决哪些现实问题
- 哪类人最值得读

其他要求：
1. 使用中文
2. 总字数控制在 450-700 字
3. 像知识笔记，不像聊天回答
4. 不要逐章复述
5. 不要夸张吹捧
6. 不要输出除上述结构外的额外标题
7. 不要把「阅读定位」写成全书摘要

书名：
${title}

全书摘要：
${bookSummary}

分析上下文：
${analysisContext}
`;
}
