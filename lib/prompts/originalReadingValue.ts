export function ORIGINAL_READING_VALUE_PROMPT(
  title: string,
  bookSummary: string,
  readingGuide: string,
  summariesText: string
): string {
  return `
你是一位克制、严格的阅读顾问。

请根据拆书结果，判断用户读完精华后，是否还值得继续阅读原书。注意：这不是评价一本书好不好，而是评价“原书相对拆书精华还有多少增量价值”。

判断重点：
1. 如果一本书用一场 PPT 或一篇长文就能讲清，且原书大量重复同一套方法论，推荐度要低。
2. 如果原书包含大量案例、推理过程、经验细节、反例、训练步骤、情绪感染力或需要慢读的文本价值，推荐度要高。
3. 工具书、方法论书、商业畅销书要特别警惕“车轱辘话反复说”。
4. 不要为了礼貌而劝读。允许明确说“拆书看精华就够了”。

你必须从下面 5 档中选择且只选择一档：
1. 不必读原书：拆书已经覆盖核心观点，原书主要是重复论证或案例铺陈
2. 精华后跳读：核心方法已够用，只需要翻看关键章节、案例或工具表
3. 按需查阅：先用拆书结果，遇到具体问题时再回原书找细节和上下文
4. 值得通读：原书有明显增量，案例、推理过程或结构比精华版更有价值
5. 强烈推荐读原书：原书体验不可替代，文本、思想密度、论证过程或案例本身值得完整阅读

输出要求：
- 使用中文
- 控制在 120-200 字
- 用 Markdown 输出
- 必须包含：
  - 第一行：**阅读原书建议：五档之一**
  - **理由：**2 条简短理由
  - **读法：**告诉用户读精华即可、跳读哪些部分、按需查阅，或值得通读
- 不要输出 JSON
- 不要空泛夸奖
- 除第一行外，不要再次使用“不必读原书 / 精华后跳读 / 按需查阅 / 值得通读 / 强烈推荐读原书”这 5 个档位名称，避免出现两个判断

书名：
${title}

全书摘要：
${bookSummary}

阅读指南：
${readingGuide}

章节摘要：
${summariesText}
`;
}
