export function VIEW_MAP_PROMPT(
  title: string,
  bookSummary: string,
  analysisContext: string
): string {
  return `
你是一位逻辑分析师。

请基于下面提供的全书摘要与分析上下文，为这本书生成一份「观点地图」。

目标：
把一本书从线性文本转换为结构化观点，帮助读者快速理解核心判断、关键观点之间的关系，以及这些观点对应的依据。

输出必须严格使用以下结构：

## 中心观点
用 1 段话提炼整本书最核心的判断。
要求：
- 不能只是主题名词
- 必须是一个清晰判断

## 关键观点
列出 3-5 条支撑中心观点的关键观点。
要求：
- 每条观点都应是完整判断
- 不要写成章节标题

## 观点关系
说明这些关键观点之间如何支撑、依赖、递进或互相补充。
要求：
- 不要重复罗列主要观点
- 要说清观点之间的结构关系

## 关键依据
按关键观点分别列出对应的关键支撑内容，可包括：
- 概念
- 论据
- 案例
- 方法
要求：
- 每条关键观点下给出 2-4 条关键支撑
- 以简洁列表呈现
- 尽量引用章节标题、样本位置或依据提示

## 结构判断
判断这本书整体更像哪种结构：
- 问题诊断 -> 方法提出 -> 案例论证
- 概念框架 -> 推理论证 -> 实践建议
- 经验叙事 -> 原则抽象 -> 行动启发
- 其他更合适的结构
要求：
- 用 1 段话说明理由
- 不要做批判性评价

其他要求：
1. 使用中文
2. 总字数控制在 450-700 字
3. 像知识笔记，不像聊天回答
4. 不要逐章复述
5. 不要输出除上述结构外的额外标题
6. 不要输出行动建议
7. 不要包含「信息噪声」，该内容留给观点校验

书名：
${title}

全书摘要：
${bookSummary}

分析上下文：
${analysisContext}
`;
}
