import {chromium} from 'playwright-core';
import {LibraryStore} from '../src/store.mjs';
import {Bridge} from '../src/bridge.mjs';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const parent = fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()), 'bookleap-browser-'));
const store = new LibraryStore(parent);
const bridge = new Bridge(store, {origins: ['http://localhost:3000'], onPair: async () => true});
await bridge.listen();
const browser = await chromium.launch({executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true});
const context = await browser.newContext();
const page = await context.newPage();
try {
  await page.goto('http://localhost:3000/workspace');
  await page.getByRole('button', {name: '我已阅读并同意'}).click();
  await page.getByRole('button', {name: '本地 MCP', exact: true}).click();
  await page.getByLabel('来源名称').fill('合成 Chrome 测试');
  await page.getByLabel('配对码', {exact:true}).fill(bridge.createPairing().code);
  await page.getByLabel('我同意同步，并了解上述数据用途。').check();
  await page.getByRole('button', {name: '配对并自动同步'}).click();
  await page.waitForFunction(() => document.querySelector('dialog[open]')?.textContent.includes('已同步'));
  console.log('empty library paired and acknowledged', store.state.sources.length);
  await page.screenshot({path: '/private/tmp/bookleap-local-mcp-panel.png'});
  await page.evaluate(async () => {
    const db = await new Promise((resolve, reject) => {const r = indexedDB.open('bookleap_workspace_v1', 1); r.onsuccess=()=>resolve(r.result); r.onerror=()=>reject(r.error);});
    const tx = db.transaction('historyRecords', 'readwrite');
    tx.objectStore('historyRecords').put({id:'synthetic-book', title:'合成长期主义', author:'测试作者', fileType:'epub', mode:'full', createdAt:'2026-11-08T00:00:00Z', bookSummary:'长期主义带来复利。',readingGuide:'先看原则，再看行动。',viewMap:'理解长期回报。',actionExtraction:'坚持阅读。',viewValidation:'观察证据。',ideaSourceTracing:'测试内容。',bookRecommendation:'',originalReadingValue:'已有值，避免调用生成 API。'});
    await new Promise((resolve,reject)=>{tx.oncomplete=resolve;tx.onerror=reject;}); db.close(); window.dispatchEvent(new Event('bookleap-history-saved'));
  });
  await page.waitForFunction(() => document.querySelector('dialog[open]')?.textContent.includes('1 本'));
  if (store.state.sources[0].books.length !== 1) throw new Error('automatic sync failed');
  console.log('new synthetic book automatically synchronized');
  await page.reload();
  await page.getByRole('button', {name: '本地 MCP', exact: true}).click();
  await page.waitForFunction(() => document.querySelector('dialog[open]')?.textContent.includes('1 本'));
  console.log('page reopen recovered same source', store.state.sources.length);
  await page.getByRole('button', {name: '暂停自动同步'}).click();
  await page.waitForFunction(() => document.querySelector('dialog[open]')?.textContent.includes('已暂停'));
  console.log('pause preserves', store.state.sources[0].books.length, 'book');
  await page.getByRole('button', {name: '恢复自动同步'}).click();
  await page.waitForFunction(() => document.querySelector('dialog[open]')?.textContent.includes('已同步'));
  await page.evaluate(() => localStorage.setItem('bookleap_reading_reflection:synthetic-book', JSON.stringify({reflection: '合成私人反思'})));
  await page.getByLabel('同时同步卡片高亮').check();
  await page.waitForFunction(() => document.querySelector('dialog[open]')?.textContent.includes('包含个人记录'));
  if (!store.state.sources[0].books[0].fragments.some(f => f.type === 'personal')) throw new Error('personal opt-in failed');
  await page.getByLabel('同时同步卡片高亮').uncheck();
  await page.waitForFunction(() => document.querySelector('dialog[open]')?.textContent.includes('仅分析与已有证据'));
  if (store.state.sources[0].books[0].fragments.some(f => f.type === 'personal')) throw new Error('personal revocation failed');
  console.log('personal opt-in and revocation applied');
  await page.getByText('选择同步书籍', {exact: false}).click();
  await page.getByLabel('合成长期主义', {exact:true}).uncheck();
  await page.waitForFunction(() => document.querySelector('dialog[open]')?.textContent.includes('0 本'));
  if (store.state.sources[0].books.length !== 0) throw new Error('exclusion not applied');
  console.log('scope exclusion removed local contribution');
  await page.screenshot({path: '/private/tmp/bookleap-local-mcp-panel-scoped.png'});
  await page.screenshot({path: '/private/tmp/bookleap-workspace-before.png'});
} finally {await browser.close(); await bridge.close(); store.close(); fs.rmSync(parent, {recursive: true, force: true});}
