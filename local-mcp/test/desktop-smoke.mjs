import {_electron as electron} from 'playwright-core';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StdioClientTransport} from '@modelcontextprotocol/sdk/client/stdio.js';
const root = fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()), 'bookleap-desktop-'));
const appRoot = path.resolve(process.argv[2] ?? 'local-mcp/dist-desktop-ui/mac-arm64/书跃本地同步助手.app');
const executablePath = process.platform === 'win32' ? appRoot : path.join(appRoot, 'Contents/MacOS/书跃本地同步助手');
const script = process.platform === 'win32' ? path.join(path.dirname(appRoot), 'resources/app/src/mcp.mjs') : path.join(appRoot, 'Contents/Resources/app/src/mcp.mjs');
const screenshot = name => path.join(os.tmpdir(), name);
let app;
try {
  app = await electron.launch({executablePath, args: ['--bookleap-test'], env: {...process.env, BOOKLEAP_TEST_HOME: root, CODEX_HOME: path.join(root, 'codex')}});
  const page = await app.firstWindow();
  await page.waitForFunction(() => document.getElementById('status').textContent.includes('后台运行中'));
  const status = await page.evaluate(() => window.bookleap.invoke('status'));
  assert.ok(status.path.toLowerCase().startsWith(root.toLowerCase())); console.log('desktop started with isolated library', status.platform);
  const test = await page.evaluate(() => window.bookleap.invoke('test'));
  assert.match(test.state, /测试成功/);
  const connection = await page.evaluate(() => window.bookleap.invoke('connection'));
  assert.equal(connection.mcpServers.bookleap.command, executablePath);
  assert.equal(connection.mcpServers.bookleap.env.BOOKLEAP_LIBRARY, status.path); console.log('packaged Electron runtime MCP SDK test passed');
  await app.evaluate(({dialog}) => {dialog.showMessageBox = async () => ({response:1});});
  await page.screenshot({path:screenshot('bookleap-ui-overview.png')});
  await page.getByRole('button',{name:'连接网页',exact:true}).click();
  const code = await page.locator('#pair').textContent();
  await page.screenshot({path:screenshot('bookleap-ui-pair.png')});
  await page.getByRole('button',{name:'完成',exact:true}).click();
  const sourceId = randomUUID();
  const headers = {'Content-Type':'application/json',Origin:'https://www.bookleap.cn','X-BookLeap-Protocol':'1'};
  const paired = await fetch('http://127.0.0.1:48724/pair',{method:'POST',headers,body:JSON.stringify({schemaVersion:1,sourceId,sourceName:'桌面合成来源',code})});
  const {token} = await paired.json(); assert.ok(token);
  const saved = await fetch('http://127.0.0.1:48724/snapshot',{method:'POST',headers:{...headers,Authorization:'Bearer '+token},body:JSON.stringify({schemaVersion:1,kind:'complete-snapshot',sourceId,baseRevision:0,requestId:randomUUID(),scope:{personal:false,excludedIds:[]},recordCount:1,books:[{sourceRecordId:'synthetic',title:'桌面合成书',author:'测试',format:'epub',analysisVersion:'1',fragments:[{id:'analysis-0',module:'bookSummary',type:'analysis',text:'长期主义与复利，桌面合成测试。'}]}]})}); assert.equal(saved.status,200);
  await page.evaluate(() => window.bookleap.invoke('pause'));
  const pausedTest = await page.evaluate(() => window.bookleap.invoke('test'));
  assert.equal(JSON.parse(pausedTest.result.content[0].text).bookCount,1);
  await page.evaluate(() => window.bookleap.invoke('pause'));
  await page.waitForFunction(() => document.getElementById('navCount').textContent === '1');
  assert.equal(await page.locator('#sourceCount').textContent(), '1');
  await page.getByRole('button',{name:'本地书库'}).click();
  await page.getByRole('button',{name:'阅读分析'}).click();
  await page.getByRole('button',{name:'核验此引用与证据'}).click();
  await page.waitForFunction(() => document.getElementById('library').textContent.includes('没有已保存的原书证据'));
  console.log('desktop paired, persisted, paused safely and rendered evidence honesty');
  const result = await page.evaluate(() => window.bookleap.invoke('configure'));
  assert.match(result, /配置已写入/); assert.ok(fs.readFileSync(path.join(root, 'codex/config.toml'), 'utf8').includes('mcp_servers.bookleap'));
  console.log('reviewed config flow wrote only isolated Codex config');
  await page.evaluate(() => window.bookleap.invoke('restore'));
  assert.equal(fs.readFileSync(path.join(root, 'codex/config.toml'), 'utf8'), '');
  await page.screenshot({path: screenshot('bookleap-local-desktop.png')});
  await page.getByRole('button',{name:'设置',exact:true}).click();
  await page.locator('#preview').check();
  assert.equal((await page.evaluate(() => window.bookleap.invoke('status'))).preview, true);
  await page.locator('#preview').uncheck();
  await page.screenshot({path:screenshot('bookleap-ui-settings.png'), animations:'disabled'});
  await app.evaluate(({BrowserWindow}) => BrowserWindow.getAllWindows()[0].setSize(820, 600));
  await page.emulateMedia({colorScheme:'dark', reducedMotion:'reduce'});
  await page.getByRole('button',{name:'同步概览',exact:true}).click();
  await page.screenshot({path:screenshot('bookleap-ui-dark.png'), animations:'disabled'});
  assert.ok(await page.evaluate(() => document.body.scrollWidth <= window.innerWidth));
  await app.evaluate(({BrowserWindow}) => BrowserWindow.getAllWindows()[0].close());
  assert.equal(await app.evaluate(({BrowserWindow}) => BrowserWindow.getAllWindows()[0].isVisible()), false);
  assert.equal((await fetch('http://127.0.0.1:48724/status', {headers:{Origin:'https://www.bookleap.cn','X-BookLeap-Protocol':'1',Authorization:'Bearer '+token}})).status, 200);
  console.log('sidebar, preview toggle, compact dark layout and close-to-background passed');
  await app.close(); app = undefined;
  const client = new Client({name:'packaged-offline-test', version:'1'});
  try {
    await client.connect(new StdioClientTransport({command: executablePath, args: [script], env: {...process.env, ELECTRON_RUN_AS_NODE:'1', BOOKLEAP_LIBRARY: status.path}, stderr:'pipe'}));
    const tools = await client.listTools(); assert.equal(tools.tools.length,5);
    const offlineStatus = await client.callTool({name:'library_status',arguments:{}}); assert.equal(JSON.parse(offlineStatus.content[0].text).bookCount,1);
    console.log('packaged runtime stdio reads persisted book after desktop exit');
  } finally {await client.close();}
} finally {if (app) await app.close(); fs.rmSync(root,{recursive:true,force:true});}
